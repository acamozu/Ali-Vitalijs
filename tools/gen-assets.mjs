// Generates the parts of the Fiori app that are taken 1:1 from the web version (branch year-end-conference-agenda):
//   webapp/css/style.css         src/styles.css, limited to the app root .agHost
//   webapp/css/skin.css          src/inkwell/skin.css, limited to .agHost with the class skin-inkwell
//   webapp/css/fonts.css         Rubik 400-700 (page), embedded as base64
//   webapp/css/fonts-skin.css    Inter 400-700 + Montserrat 700-900 (only for the skin), embedded as base64
//   webapp/model/icons.js        the lucide icons the page uses, as SVG strings
//
//   node tools/gen-assets.mjs [path of the web version]      (default: ../Github_Ali_Vitalijs_year-end-conference-agenda)
//
// The web version must have its packages installed (npm install): postcss, the fonts and the icons are read from there.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createRequire } from "node:module";

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, "..", "webapp");
const web = path.resolve(process.argv[2] || path.resolve(here, "..", "..", "Github_Ali_Vitalijs_year-end-conference-agenda"));
const require = createRequire(path.join(web, "package.json"));
const postcss = require("postcss");

const write = (file, text) => {
  fs.mkdirSync(path.dirname(path.join(app, file)), { recursive: true });
  fs.writeFileSync(path.join(app, file), text.replace(/\r\n/g, "\n"));
  console.log(`${file}  ${(Buffer.byteLength(text) / 1024).toFixed(0)} KB`);
};

// ---------- CSS ----------
// Every rule is limited to the app root, so nothing leaks into the Fiori Launchpad around the app. The order of the
// rules is unchanged and every class rule gets the same prefix, so the cascade is the one of the original.
const KEYFRAMES = {}; // original name -> name in the app (keyframe names are global)

function scope(source, root, header) {
  const ast = postcss.parse(source);
  ast.walkAtRules("keyframes", (at) => {
    KEYFRAMES[at.params] = `ag-${at.params}`;
  });
  ast.walkAtRules("keyframes", (at) => {
    at.params = KEYFRAMES[at.params];
  });
  ast.walkDecls(/^animation(-name)?$/, (decl) => {
    Object.keys(KEYFRAMES).forEach((name) => {
      decl.value = decl.value.replace(new RegExp(`(^|[\\s,])${name}(?=$|[\\s,])`, "g"), `$1${KEYFRAMES[name]}`);
    });
  });
  ast.walkRules((rule) => {
    if (rule.parent.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
    rule.selectors = rule.selectors.map((sel) => {
      const s = sel.trim();
      if (s === ":root" || s === "body") return root;
      if (s === "body:has(.ag)") return `${root}:has(.ag)`;
      if (s === "*") return `${root}, ${root} *`;
      if (s === "*::-webkit-scrollbar") return `${root}::-webkit-scrollbar, ${root} *::-webkit-scrollbar`;
      if (/^(h[1-6]|p)$/.test(s)) return `${root} :where(${s})`; // bare elements keep their low priority
      return `${root} ${s}`;
    });
  });
  return header + ast.toString() + "\n";
}

write(
  "css/style.css",
  scope(
    fs.readFileSync(path.join(web, "src/styles.css"), "utf8"),
    ".agHost",
    "/* GENERATED by tools/gen-assets.mjs from src/styles.css of the web version - do not edit, change the web version.\n" +
      "   Same rules in the same order; every selector is limited to the app root .agHost (:root / body = .agHost),\n" +
      "   keyframes are renamed to ag-*. What only the Fiori version needs is in host.css. */\n"
  )
);
write(
  "css/skin.css",
  scope(
    fs.readFileSync(path.join(web, "src/inkwell/skin.css"), "utf8"),
    // :where() adds no priority: skin and page rules keep the relation they have in the web version
    ".agHost:where(.skin-inkwell)",
    "/* GENERATED by tools/gen-assets.mjs from src/inkwell/skin.css of the web version - do not edit.\n" +
      "   Loaded only for the carpool look (inkwell.html or ?skin=inkwell); limited to .agHost with the class skin-inkwell. */\n"
  )
);

// ---------- fonts ----------
// Embedded as base64: the deployment to the ABAP repository stores .woff2 files as text and breaks them.
function fonts(list, note) {
  let css = `/* GENERATED by tools/gen-assets.mjs. ${note}\n   Subsets latin and latin-ext, embedded as base64 (no request to a font server, no binary font files in the app). */\n`;
  list.forEach(({ family, pkg, weights }) => {
    const src = fs.readFileSync(path.join(web, "node_modules", "@fontsource", pkg, "index.css"), "utf8");
    weights.forEach((weight) => {
      ["latin-ext", "latin"].forEach((subset) => {
        const file = path.join(web, "node_modules", "@fontsource", pkg, "files", `${pkg}-${subset}-${weight}-normal.woff2`);
        const block = new RegExp(`/\\* ${pkg}-${subset}-400-normal \\*/[^}]*unicode-range:\\s*([^;]+);`).exec(src);
        if (!block) throw new Error(`unicode-range of ${pkg} ${subset} not found`);
        css += `@font-face { font-family: "${family}"; font-style: normal; font-display: swap; font-weight: ${weight}; src: url(data:font/woff2;base64,${fs.readFileSync(file).toString("base64")}) format("woff2"); unicode-range: ${block[1].trim()}; }\n`;
      });
    });
  });
  return css;
}
write("css/fonts.css", fonts([{ family: "Rubik", pkg: "rubik", weights: [400, 500, 600, 700] }], "Font of the page: Rubik (SIL Open Font License), weights 400-700."));
write(
  "css/fonts-skin.css",
  fonts(
    [
      { family: "Inter", pkg: "inter", weights: [400, 500, 600, 700] },
      { family: "Montserrat", pkg: "montserrat", weights: [700, 800, 900] },
    ],
    "Fonts of the carpool look: Inter 400-700 and Montserrat 700-900 (SIL Open Font License)."
  )
);

